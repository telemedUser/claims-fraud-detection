"""Byte-level document forensics. Pure, no I/O.

* Incremental updates: a PDF that was edited and saved "incrementally" keeps the original revision and
  appends a new one. Each revision ends with its own ``%%EOF`` marker, so more than one marker means the
  file changed after it was first produced. Digital signatures and some form fillers also do this.
* AI-generation markers: generator names in PDF or image metadata (Producer, Creator, XMP, EXIF Software)
  and IPTC/C2PA provenance labels such as ``trainedAlgorithmicMedia``. A marker is an indicator, never proof,
  and its absence proves nothing (markers are easy to strip).
"""
from __future__ import annotations

import re

AI_MARKERS = (
    "chatgpt", "openai", "dall-e", "dall·e", "dalle", "midjourney", "stable diffusion", "stablediffusion",
    "adobe firefly", "firefly", "gemini", "google bard", "copilot designer", "bing image creator",
    "magic design", "magic write", "ai generated", "ai-generated", "generated by ai", "leonardo.ai",
    "trainedalgorithmicmedia", "compositewithtrainedalgorithmicmedia", "c2pa",
)


def revision_count(data: bytes) -> int:
    """Number of saved revisions of a PDF (count of %%EOF markers); 0 for non-PDF data."""
    if not data or not data[:1024].lstrip().startswith(b"%PDF"):
        return 0
    return len(re.findall(rb"%%EOF", data))


def ai_markers(data: bytes, metadata_values: list[str] | None = None) -> list[str]:
    """AI-generation markers found in metadata values or in the raw bytes (XMP/EXIF are stored as text)."""
    found: list[str] = []
    hay_meta = " ".join(str(v) for v in (metadata_values or []) if v).lower()
    hay_raw = (data or b"")[:4_000_000].lower()
    for marker in AI_MARKERS:
        if marker in hay_meta or marker.encode("utf-8") in hay_raw:
            found.append(marker)
    # "gemini" and "c2pa" alone are weak (product names, empty manifests); keep them only with metadata support
    strong = [m for m in found if m not in ("gemini", "c2pa") or m in hay_meta]
    return strong
